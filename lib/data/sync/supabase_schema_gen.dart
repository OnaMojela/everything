import 'package:drift/drift.dart';

import 'sync_schema.dart';

/// Generates the Supabase (Postgres) mirror schema from the live Drift schema.
///
/// Keeping this generated rather than hand-written means a column added to a
/// Drift table cannot silently go missing on the server; `supabase_schema_test`
/// fails whenever the checked-in SQL no longer matches the app's tables.
///
/// Two deliberate differences from the local schema:
///
/// * **No foreign keys.** The server is a mirror, not the authority — SQLite
///   enforces referential integrity locally, where the app actually reads.
///   Leaving them off means a push or pull can apply tables in any order
///   without tripping a constraint that the local database will re-establish
///   anyway.
/// * **Soft deletes.** A removed row is kept with `sync_deleted = true` so
///   other devices can learn that it went away. Hard-deleting would make the
///   deletion invisible to every device that had not yet pulled.
String generateSupabaseSchema(GeneratedDatabase db) {
  final tables = {for (final t in db.allTables) t.actualTableName: t};
  final buffer = StringBuffer()
    ..writeln('-- Generated by lib/data/sync/supabase_schema_gen.dart.')
    ..writeln('-- Do not edit by hand: regenerate with')
    ..writeln('--   flutter test test/supabase_schema_test.dart '
        '--dart-define=WRITE=1')
    ..writeln('--')
    ..writeln('-- Mirror of the app\'s local SQLite schema, one row per user.')
    ..writeln('-- Datetimes are stored the way Drift stores them locally, as')
    ..writeln('-- unix seconds in a bigint, so sync is a pure passthrough.')
    ..writeln();

  for (final table in syncedTables) {
    final info = tables[table.name];
    if (info == null) {
      throw StateError('Synced table "${table.name}" is not in the database.');
    }
    buffer
      ..writeln('-- ${'-' * 72}')
      ..writeln('create table if not exists public.${table.name} (')
      ..writeln('  user_id uuid not null references auth.users(id) '
          'on delete cascade,');

    for (final column in info.$columns) {
      if (column.type case final DriftSqlType driftType) {
        final nullable = column.$nullable ? '' : ' not null';
        buffer.writeln('  ${column.name} ${_postgresType(driftType)}$nullable,');
      } else {
        throw ArgumentError(
          'Column ${table.name}.${column.name} uses a custom SQL type, which '
          'the Supabase mirror has no mapping for.',
        );
      }
    }

    buffer
      ..writeln('  sync_updated_at timestamptz not null default now(),')
      ..writeln('  sync_deleted boolean not null default false,')
      ..writeln('  primary key (user_id, ${table.key})')
      ..writeln(');')
      ..writeln()
      // The pull cursor scans by user and change time; this index is what
      // keeps an incremental sync from reading the whole table.
      ..writeln('create index if not exists ${table.name}_sync_idx')
      ..writeln('  on public.${table.name} (user_id, sync_updated_at);')
      ..writeln()
      ..writeln('alter table public.${table.name} enable row level security;')
      ..writeln()
      ..writeln('drop policy if exists ${table.name}_owner '
          'on public.${table.name};')
      ..writeln('create policy ${table.name}_owner on public.${table.name}')
      ..writeln('  for all to authenticated')
      ..writeln('  using (auth.uid() = user_id)')
      ..writeln('  with check (auth.uid() = user_id);')
      ..writeln()
      ..writeln('drop trigger if exists ${table.name}_touch '
          'on public.${table.name};')
      ..writeln('create trigger ${table.name}_touch')
      ..writeln('  before insert or update on public.${table.name}')
      ..writeln('  for each row execute function public.touch_sync_updated_at();')
      ..writeln();
  }

  return '${_preamble.trimRight()}\n\n${buffer.toString().trimRight()}\n';
}

/// `sync_updated_at` is stamped by the database, never by the client. Devices
/// disagree about the time — often by minutes, occasionally by hours — and a
/// pull cursor built on client clocks would skip or replay rows. One server
/// clock makes the ordering total and trustworthy.
const _preamble = '''
create or replace function public.touch_sync_updated_at()
returns trigger
language plpgsql
as \$\$
begin
  new.sync_updated_at = now();
  return new;
end;
\$\$;
''';

String _postgresType(DriftSqlType type) => switch (type) {
      DriftSqlType.string => 'text',
      DriftSqlType.int => 'bigint',
      DriftSqlType.bigInt => 'bigint',
      DriftSqlType.bool => 'boolean',
      DriftSqlType.double => 'double precision',
      // Drift stores datetimes as unix seconds unless configured otherwise;
      // mirroring that keeps push and pull free of any date parsing.
      DriftSqlType.dateTime => 'bigint',
      DriftSqlType.blob => 'bytea',
      _ => throw ArgumentError('No Postgres mapping for $type'),
    };
